import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive

/**
 * Reads app_config.json from assets and exposes parameters as editable state.
 * Falls back to benchmark_config.json (legacy) if app_config.json is not present.
 */
class SettingsViewModel : ViewModel() {

    val parameters = mutableStateMapOf<String, String>()
    var loaded = false
        private set

    private var prefs: SharedPreferences? = null

    companion object {
        private const val PREFS_NAME = "mnn_settings"
        private const val PREFS_KEY_SAVED = "has_saved_settings"
    }

    fun loadConfig(context: Context) {
        if (loaded) return
        prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)

        try {
            // Try SharedPreferences first (user-modified settings persist here)
            if (tryLoadFromPrefs()) {
                parameters.remove("enable_op_profile")
                loaded = true
                return
            }
            // Fall back to asset JSON
            if (tryLoadAppConfig(context) || tryLoadBenchmarkConfig(context)) {
                parameters.remove("enable_op_profile")
                loaded = true
            }
        } catch (_: Exception) {
            // Config may not exist yet
        }
    }

    private fun tryLoadFromPrefs(): Boolean {
        val p = prefs ?: return false
        if (!p.getBoolean(PREFS_KEY_SAVED, false)) return false
        val all = p.all
        for ((key, value) in all) {
            if (key == PREFS_KEY_SAVED) continue
            parameters[key] = value.toString()
        }
        return parameters.isNotEmpty()
    }

    private fun saveToPrefs() {
        val p = prefs ?: return
        val editor = p.edit()
        editor.clear()
        editor.putBoolean(PREFS_KEY_SAVED, true)
        for ((key, value) in parameters) {
            editor.putString(key, value)
        }
        editor.apply()
    }

    /** Load from app_config.json (flat structure generated by AppBuilder). */
    private fun tryLoadAppConfig(context: Context): Boolean {
        return try {
            val jsonStr = context.assets.open("app_config.json")
                .bufferedReader().use { it.readText() }
            val json = Json.parseToJsonElement(jsonStr).jsonObject

            // Keys handled separately (arrays/objects with custom flattening)
            val specialKeys = setOf("hints", "gpu_mode", "session_mode")
            // Flatten sections into parameters map
            for (section in listOf("engine", "sampler", "generation")) {
                json[section]?.jsonObject?.forEach { (key, value) ->
                    if (key !in specialKeys) {
                        parameters[key] = extractPrimitiveValue(value)
                    }
                }
            }
            // Flatten hints sub-object: each hint becomes "hint_<KEY>" in the map
            json["engine"]?.jsonObject?.get("hints")?.jsonObject?.forEach { (key, value) ->
                parameters["hint_$key"] = extractPrimitiveValue(value)
            }
            // Flatten gpu_mode list into comma-separated string
            json["engine"]?.jsonObject?.get("gpu_mode")?.let { elem ->
                if (elem is kotlinx.serialization.json.JsonArray) {
                    parameters["gpu_mode"] = elem.joinToString(",") {
                        it.jsonPrimitive.content
                    }
                }
            }
            // Flatten session_mode list into comma-separated string
            json["engine"]?.jsonObject?.get("session_mode")?.let { elem ->
                if (elem is kotlinx.serialization.json.JsonArray) {
                    parameters["session_mode"] = elem.joinToString(",") {
                        it.jsonPrimitive.content
                    }
                }
            }
            true
        } catch (_: Exception) {
            false
        }
    }

    /** Fallback: load from benchmark_config.json (legacy, first enabled stage). */
    private fun tryLoadBenchmarkConfig(context: Context): Boolean {
        return try {
            val jsonStr = context.assets.open("benchmark_config.json")
                .bufferedReader().use { it.readText() }
            val json = Json.parseToJsonElement(jsonStr).jsonObject

            val stages = json["stages"]
            if (stages is kotlinx.serialization.json.JsonArray) {
                val firstEnabled = stages.firstOrNull { elem ->
                    val obj = elem.jsonObject
                    val enabled = obj["enabled"]?.jsonPrimitive?.content
                    enabled != "false"
                }?.jsonObject

                firstEnabled?.forEach { (key, value) ->
                    if (key != "name" && key != "enabled") {
                        parameters[key] = extractPrimitiveValue(value)
                    }
                }
            }

            json["device"]?.jsonObject?.let { device ->
                device["thermal_target"]?.let {
                    parameters["thermal_target"] = extractPrimitiveValue(it)
                }
            }
            true
        } catch (_: Exception) {
            false
        }
    }

    fun updateParameter(key: String, value: String) {
        parameters[key] = value
        saveToPrefs()
    }

    /** Returns true if the current backend is a GPU backend (not CPU). */
    fun isGpuBackend(): Boolean {
        val backend = parameters["backend"] ?: "cpu"
        return backend != "cpu"
    }

    /**
     * Serialize current settings to a JSON string for passing to native set_config().
     * Reconstructs hints as a nested object, gpu_mode/session_mode as arrays.
     */
    fun toConfigJson(): String {
        val sb = StringBuilder("{")
        var first = true
        val hintEntries = mutableMapOf<String, String>()

        for ((key, value) in parameters) {
            if (key.startsWith("hint_")) {
                hintEntries[key.removePrefix("hint_")] = value
                continue
            }
            if (!first) sb.append(",")
            first = false

            when (key) {
                "gpu_mode", "session_mode" -> {
                    // Emit as JSON array of strings
                    val items = value.split(",").filter { it.isNotBlank() }
                    sb.append("\"$key\":[")
                    sb.append(items.joinToString(",") { "\"${it.trim()}\"" })
                    sb.append("]")
                }
                else -> {
                    // Try to emit as number or boolean, fallback to string
                    val numVal = value.toDoubleOrNull()
                    val boolVal = when (value) {
                        "true" -> "true"
                        "false" -> "false"
                        else -> null
                    }
                    when {
                        boolVal != null -> sb.append("\"$key\":$boolVal")
                        numVal != null -> {
                            if (numVal == numVal.toLong().toDouble()) {
                                sb.append("\"$key\":${numVal.toLong()}")
                            } else {
                                sb.append("\"$key\":$numVal")
                            }
                        }
                        else -> sb.append("\"$key\":\"$value\"")
                    }
                }
            }
        }

        // Emit hints as nested object
        if (hintEntries.isNotEmpty()) {
            if (!first) sb.append(",")
            sb.append("\"hints\":{")
            sb.append(hintEntries.entries.joinToString(",") { (k, v) ->
                val numV = v.toIntOrNull()
                if (numV != null) "\"$k\":$numV" else "\"$k\":\"$v\""
            })
            sb.append("}")
        }

        sb.append("}")
        return sb.toString()
    }

    private fun extractPrimitiveValue(element: JsonElement): String {
        return when (element) {
            is JsonPrimitive -> element.content
            is JsonObject -> element.toString()
            else -> element.toString()
        }
    }
}

